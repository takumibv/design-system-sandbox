const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, locale: 'ja-JP' }); const p = await ctx.newPage()
  const errs = []; p.on('pageerror', e => errs.push(String(e))); p.on('console', m => m.type()==='error' && errs.push(m.text()))
  const log = (...a) => console.log(...a)
  await p.goto('http://localhost:5173/?as=editor'); await p.waitForLoadState('networkidle')
  log('logo', await p.locator('.smarthr-ui-Header-logoLink').evaluateAll(as => as.map(a => a.href + ' ' + a.target)))
  await p.getByRole('button', { name: '投稿を追加' }).first().click()
  await p.getByRole('button', { name: '追加', exact: true }).click()
  log('validation shown:', await p.getByText('タイトルを入力してください').count())
  await p.getByRole('textbox', { name: 'タイトル' }).fill('E2E テスト投稿')
  await p.locator('input[name=plannedDate]').fill('2026-11-24')
  await p.getByRole('button', { name: '追加', exact: true }).click()
  await p.waitForTimeout(300); log('url after add', p.url()); log('notice', await p.getByText('投稿を追加しました').count())
  await p.getByRole('button', { name: '公開済みにする' }).click()
  await p.locator('input[name=url]').fill('https://example.com/blog/99')
  await p.getByRole('dialog').getByRole('button', { name: '公開済みにする' }).click()
  await p.waitForTimeout(300); log('published notice', await p.getByText('投稿を公開済みにしました').count(), 'label', await p.getByText('公開済み', { exact: true }).count())
  await p.getByRole('button', { name: '操作' }).click(); await p.getByText('削除', { exact: true }).click()
  await p.getByRole('dialog').getByRole('button', { name: '削除', exact: true }).click()
  await p.waitForTimeout(300); log('after delete', p.url(), await p.getByText('投稿を削除しました').count(), 'still listed', await p.getByText('E2E テスト投稿').count())
  // edit own as member and gap disappears check
  await p.goto('http://localhost:5173/?as=guest'); await p.waitForLoadState('networkidle')
  await p.getByRole('button', { name: 'Slackでログイン' }).first().click(); await p.waitForTimeout(300)
  log('login', p.url(), await p.getByText('Slackでログインしました').count())
  // client nav keeps state: add then go to mine
  await p.getByRole('button', { name: '投稿を追加' }).first().click()
  await p.getByRole('textbox', { name: 'タイトル' }).fill('状態保持テスト')
  await p.getByRole('button', { name: '追加', exact: true }).click(); await p.waitForTimeout(300)
  await p.getByRole('link', { name: '自分の担当' }).first().click(); await p.waitForTimeout(300)
  log('mine has new', await p.getByText('状態保持テスト').count())
  await p.goto('http://localhost:5173/?from=2026-12-01&to=2026-11-01'); await p.waitForLoadState('networkidle')
  await p.locator('input[name=from]').fill('2026-12-01'); await p.locator('input[name=to]').fill('2026-11-01')
  await p.getByRole('button', { name: '表示' }).click(); log('period error', await p.getByText('終了日は開始日より後').count())
  log('errors', errs)
  await b.close()
})()
